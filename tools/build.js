#!/usr/bin/env node
/* Regenerate bundle.md + manifest.json from the per-card files.
   Run after adding/editing any {topic}/NN_slug_level.md card. */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const TOPICS = fs.readdirSync(ROOT).filter(d =>
  fs.statSync(path.join(ROOT, d)).isDirectory() && !d.startsWith(".") && d !== "tools" && d !== "node_modules");

// merge skill trees into one skills.json the app fetches
const treeDir = path.join(ROOT, "skilltrees");
if (fs.existsSync(treeDir)) {
  const trees = fs.readdirSync(treeDir).filter(f => f.endsWith(".json")).sort()
    .map(f => JSON.parse(fs.readFileSync(path.join(treeDir, f), "utf8")));
  fs.writeFileSync(path.join(ROOT, "skills.json"), JSON.stringify({ trees }, null, 1));
  const nodes = trees.reduce((n, t) => n + t.nodes.length, 0);
  console.log(`${trees.length} skill trees, ${nodes} nodes -> skills.json`);
}

const cards = [];
for (const topic of TOPICS.filter(t => t !== "skilltrees").sort()) {
  const files = fs.readdirSync(path.join(ROOT, topic)).filter(f => f.endsWith(".md")).sort();
  for (const file of files) {
    let body = fs.readFileSync(path.join(ROOT, topic, file), "utf8").replace(/\s+$/, "") + "\n";
    // tolerate a preamble (H1, intro prose) — cards start at the first "## type:"
    const start = body.search(/^##\s+\w+:/m);
    if (start === -1) { console.warn(`skip (no card header): ${topic}/${file}`); continue; }
    body = body.slice(start);
    const m = body.match(/^##\s+(\w+):\s*(.+)/);
    if (!m) continue;
    const track = (body.match(/^track:\s*(\S+)/m) || [])[1] || "core";
    const level = (body.match(/^difficulty:\s*(\S+)/m) || [])[1] ||
      (file.match(/_([a-z]+)\.md$/) || [])[1] || "concept";
    cards.push({ topic, file: `${topic}/${file}`, type: m[1], track, level, title: m[2].trim(), body });
  }
}

fs.writeFileSync(path.join(ROOT, "bundle.md"),
  "<!-- generated by tools/build.js — edit the per-card files, not this -->\n\n" +
  cards.map(c => c.body).join("\n"));
fs.writeFileSync(path.join(ROOT, "manifest.json"),
  JSON.stringify({ count: cards.length, cards: cards.map(({ body, ...c }) => c) }, null, 1));

const byTopic = {};
for (const c of cards) byTopic[c.topic] = (byTopic[c.topic] || 0) + 1;
console.log(`${cards.length} cards ->`, byTopic);
